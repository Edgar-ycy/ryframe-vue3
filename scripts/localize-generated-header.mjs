import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const output = process.argv[2]
if (!output || process.argv.length !== 3) {
  throw new Error('usage: localize-generated-header.mjs <typescript-file>')
}

const sourcePath = path.resolve(output)
const source = await readFile(sourcePath, 'utf8')
const generatedHeader = `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n`
const localizedHeader = `/**\n * 此文件由 openapi-typescript 自动生成。\n * 请勿直接修改此文件。\n */\n`

if (!source.startsWith(generatedHeader)) {
  throw new Error(`${output} does not contain the expected openapi-typescript header`)
}

await writeFile(sourcePath, source.replace(generatedHeader, localizedHeader), 'utf8')
