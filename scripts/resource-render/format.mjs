export function header(resource, version) {
  return `// @generated by RyFrame ${version}\n// resource: ${resource.name}\n// source: ${resource.source_path}\n// 请勿手工修改；修改资源清单后重新生成。\n\n`
}

export function htmlHeader(resource, version) {
  return `<!-- @generated by RyFrame ${version} | resource: ${resource.name} | source: ${resource.source_path} -->\n<!-- 请勿手工修改；修改资源清单后重新生成。 -->\n`
}

export function hasDateColumn(resource) {
  return resource.fields.some(
    (field) =>
      field.usage.list &&
      Object.keys(field.enum_values).length === 0 &&
      field.value_type === 'date_time',
  )
}
