import type { ResourceField } from './resource.ts'
import type { EnumField } from './values.ts'

export interface ResourceSource {
  name: string
  source_path: string
}

export function header(resource: ResourceSource, version: string): string {
  return `// @generated by RyFrame ${version}\n// resource: ${resource.name}\n// source: ${resource.source_path}\n// 请勿手工修改；修改资源清单后重新生成。\n\n`
}

export function htmlHeader(resource: ResourceSource, version: string): string {
  return `<!-- @generated by RyFrame ${version} | resource: ${resource.name} | source: ${resource.source_path} -->\n<!-- 请勿手工修改；修改资源清单后重新生成。 -->\n`
}

type DateColumnField = Pick<ResourceField, 'usage' | 'value_type'> & EnumField

export function hasDateColumn(resource: { fields: readonly DateColumnField[] }): boolean {
  return resource.fields.some(
    (field) =>
      field.usage.list &&
      Object.keys(field.enum_values).length === 0 &&
      field.value_type === 'date_time',
  )
}
