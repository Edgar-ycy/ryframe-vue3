import { renderFields } from './fields.mjs'
import { renderTransport } from './transport.mjs'

function validateAsset(asset) {
  const maxLines = asset.path.endsWith('.vue') ? 600 : 300
  if (asset.content.replace(/\n$/, '').split('\n').length > maxLines) {
    throw new Error(`生成文件超过 ${maxLines} 行：${asset.path}；请按职责拆分模板`)
  }
  if (!asset.content.includes('@generated by RyFrame')) {
    throw new Error(`生成文件缺少版本头：${asset.path}`)
  }
  if (asset.content.includes('\r')) throw new Error(`生成文件必须使用 LF：${asset.path}`)
}

export function renderResourceAssets(resources, generatorVersion, { aggregate = false } = {}) {
  if (!Array.isArray(resources)) throw new TypeError('资源集合必须是数组')
  if (
    typeof generatorVersion !== 'string' ||
    !generatorVersion ||
    /[\r\n]/.test(generatorVersion)
  ) {
    throw new TypeError('必须提供单行生成器版本')
  }
  if (typeof aggregate !== 'boolean') throw new TypeError('聚合选择必须为布尔值')
  const ordered = [...resources].sort((left, right) =>
    left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
  )
  const names = new Set()
  const assets = []
  for (const resource of ordered) {
    if (!/^[a-z][a-z0-9_]*$/.test(resource.name))
      throw new Error('资源名称不是安全的 snake_case 标识')
    if (names.has(resource.name)) throw new Error(`资源重复：${resource.name}`)
    names.add(resource.name)
    for (const [path, content] of [
      ...renderTransport(resource, generatorVersion),
      ...renderFields(resource, generatorVersion),
    ]) {
      assets.push({
        resource: resource.name,
        root: 'frontend',
        path: `src/generated/resources/${resource.name}/${path}`,
        content,
      })
    }
  }
  if (aggregate) {
    const exports = ordered.map((resource) => `export * from './${resource.name}'`).join('\n')
    assets.push({
      resource: '__catalog__',
      root: 'frontend',
      path: 'src/generated/resources/index.ts',
      content: `// @generated by RyFrame ${generatorVersion}\n// 请勿手工修改；修改资源清单后重新生成。\n\n${exports}\n`,
    })
  }
  const paths = new Set()
  for (const asset of assets) {
    if (paths.has(asset.path)) throw new Error(`生成文件路径重复：${asset.path}`)
    paths.add(asset.path)
    validateAsset(asset)
  }
  return assets.sort((left, right) =>
    left.path < right.path ? -1 : left.path > right.path ? 1 : 0,
  )
}
