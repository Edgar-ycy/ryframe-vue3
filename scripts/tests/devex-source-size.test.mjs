import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

const cli = fileURLToPath(new URL('../devex-source-size.mjs', import.meta.url))
const ownership = 'src/api/generated/ownership.json'
const lines = (count, newline = '\n') => `line${newline}`.repeat(count)

function fixture(t, files, owned = []) {
  const directory = mkdtempSync(path.resolve(import.meta.dirname, '../../.devex-source-size-'))
  t.after(() => rmSync(directory, { recursive: true, force: true }))
  const root = path.join(directory, 'frontend')
  mkdirSync(root)
  const git = (...args) => execFileSync('git', ['-C', root, ...args], { windowsHide: true })
  const write = (file, source) => {
    const destination = path.join(root, file)
    mkdirSync(path.dirname(destination), { recursive: true })
    writeFileSync(destination, source)
  }
  const manifest = (...files) =>
    write(
      ownership,
      JSON.stringify({
        version: 1,
        generator: 'scripts/generate-api-artifacts.mjs',
        files: [ownership, ...files],
      }),
    )
  git('init', '-q')
  git('config', 'core.autocrlf', 'false')
  manifest(...owned)
  for (const [file, source] of Object.entries(files)) write(file, source)
  git('add', '--', '.')
  const run = (selected = root) =>
    spawnSync(process.execPath, [cli, '--root', selected], { encoding: 'utf8', windowsHide: true })
  return { directory, root, write, manifest, run }
}

test('当前上限包含等号，工作树实际字节按 LF、CRLF、CR 计算', (t) => {
  const f = fixture(t, {
    'src/view.vue': lines(600, '\r\n'),
    'src/model.d.ts': lines(300, '\r'),
    'src/styles/main.scss': lines(300),
    'scripts/dev.config.mts': '',
    'scripts/compat.cts': 'line',
    'src/window.tsx': 'line',
    'scripts/helper.mjs': lines(501),
    'README.md': lines(150),
    '.github/template.md': lines(900),
  })
  f.write('local.vue', lines(601))
  const accepted = f.run()
  assert.equal(accepted.status, 0, accepted.stderr)
  const { groups } = JSON.parse(accepted.stdout)
  assert.deepEqual(
    Object.values(groups).map(({ files, max_lines }) => [files, max_lines]),
    [
      [1, 600],
      [4, 300],
      [1, 300],
      [1, 501],
      [1, 150],
    ],
  )

  f.write('src/view.vue', lines(600, '\r\n') + 'last')
  f.write('src/model.d.ts', lines(301, '\r'))
  f.write('src/styles/main.scss', lines(301))
  const rejected = f.run()
  assert.equal(rejected.status, 1)
  assert.deepEqual(JSON.parse(rejected.stdout).violations, [
    { path: 'src/model.d.ts', lines: 301, limit: 300 },
    { path: 'src/styles/main.scss', lines: 301, limit: 300 },
    { path: 'src/view.vue', lines: 601, limit: 600 },
  ])
})

test('只排除有登记和生成证据的实际资产', (t) => {
  const openapiHeader = '/**\n * 此文件由 OpenAPI 契约自动生成。\n */\n'
  const pluginHeader = '// Generated by unplugin-auto-import\n'
  const ryframeHeader = '// @generated by RyFrame 1.3.0\n'
  const f = fixture(
    t,
    {
      'vite.config.ts': [
        "import AutoImport from 'unplugin-auto-import/vite'",
        'const plugins = [',
        '  AutoImport({',
        "    dts: 'src/auto-imports.d.ts',",
        '  }),',
        ']',
      ].join('\n'),
      'src/auto-imports.d.ts': pluginHeader + lines(310),
      'src/components.d.ts': '// Generated by unplugin-vue-components\n' + lines(310),
      'src/api/generated/schema/core.ts': openapiHeader + lines(310),
      'src/api/generated/schema/manual.ts': openapiHeader + lines(310),
      'src/generated/resources/index.ts': ryframeHeader + lines(310),
      'src/generated/resources/post/page.vue':
        '<!-- @generated by RyFrame 1.3.0 | resource: post | source: catalog/resources/post.toml -->\n' +
        lines(610),
      'src/generated/resources/post/api.ts':
        ryframeHeader +
        '// resource: notice\n// source: catalog/resources/notice.toml\n' +
        lines(310),
      'src/generated/resources/post/extra.ts':
        ryframeHeader + '// resource: post\n// source: catalog/resources/post.toml\n' + lines(310),
    },
    ['src/api/generated/schema/core.ts'],
  )
  const result = f.run()
  assert.equal(result.status, 1)
  const report = JSON.parse(result.stdout)
  assert.deepEqual(report.excluded, {
    openapi_typescript: 1,
    vite_typescript: 1,
    resource_typescript: 1,
    resource_vue: 1,
  })
  assert.deepEqual(
    report.violations.map((row) => row.path),
    [
      'src/api/generated/schema/manual.ts',
      'src/components.d.ts',
      'src/generated/resources/post/api.ts',
      'src/generated/resources/post/extra.ts',
    ],
  )

  f.manifest('src/api/generated/schema/not-registered.ts')
  const invalid = f.run()
  assert.equal(invalid.status, 1)
  assert.match(invalid.stderr, /OpenAPI 归属清单无效/u)
})

test('拒绝非 Git 根、越界参数及指向其他目录的源码路径', (t) => {
  const f = fixture(t, { 'src/model/data.ts': 'line' })
  assert.match(f.run(path.join(f.root, 'src')).stderr, /实际的前端 Git 根/u)
  assert.match(f.run(`${f.root}${path.sep}..${path.sep}frontend`).stderr, /无效路径分量/u)
  const outside = path.join(f.directory, 'outside')
  mkdirSync(outside)
  writeFileSync(path.join(outside, 'data.ts'), 'external')
  const source = path.join(f.root, 'src/model')
  rmSync(source, { recursive: true })
  symlinkSync(outside, source, process.platform === 'win32' ? 'junction' : 'dir')
  const result = f.run()
  assert.equal(result.status, 1)
  assert.equal(result.stdout, '')
  assert.match(result.stderr, /源码路径必须是原位置的普通目录：src\/model\/data\.ts/u)
})
