import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

import { renderResourceAssets } from '../resource-render/index.mjs'

const resources = await Promise.all(
  ['post', 'notice'].map(async (name) =>
    JSON.parse(
      await readFile(new URL(`./fixtures/resource-render/${name}.json`, import.meta.url), 'utf8'),
    ),
  ),
)

test('整批前端资产与既有生成文件逐字节一致，输入顺序不改变结果', async () => {
  const before = JSON.stringify(resources)
  const assets = renderResourceAssets(resources, '1.3.0', { aggregate: true })
  assert.deepEqual(
    assets,
    renderResourceAssets([...resources].reverse(), '1.3.0', { aggregate: true }),
  )
  for (const asset of assets) {
    assert.equal(asset.root, 'frontend')
    assert.equal(
      asset.content,
      await readFile(new URL(`../../${asset.path}`, import.meta.url), 'utf8'),
      asset.path,
    )
  }
  assert.equal(JSON.stringify(resources), before)
  assert(assets.some((asset) => asset.resource === '__catalog__'))
})

test('业务批次不生成框架聚合入口，空批次保持确定性', () => {
  assert(
    renderResourceAssets(resources, '1.3.0').every((asset) => asset.resource !== '__catalog__'),
  )
  assert.deepEqual(renderResourceAssets([], '1.3.0'), [])
  assert.deepEqual(renderResourceAssets([], '1.3.0', { aggregate: true }), [
    {
      resource: '__catalog__',
      root: 'frontend',
      path: 'src/generated/resources/index.ts',
      content: '// @generated by RyFrame 1.3.0\n// 请勿手工修改；修改资源清单后重新生成。\n\n\n',
    },
  ])
})

test('重复资源及越界名称在整批返回前失败', () => {
  assert.throws(() => renderResourceAssets([resources[0], resources[0]], '1.3.0'), /资源重复/)
  for (const name of ['../post', 'post/foreign', 'post\\foreign', 'post\nforeign', 'Post', '']) {
    assert.throws(() => renderResourceAssets([{ ...resources[0], name }], '1.3.0'), /安全/)
  }
  for (const version of ['', null, '1.3.0\n']) {
    assert.throws(() => renderResourceAssets(resources, version), /版本/)
  }
  assert.throws(() => renderResourceAssets(resources, '1.3.0', { aggregate: 1 }), /布尔/)
})
