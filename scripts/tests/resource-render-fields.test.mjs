import assert from 'node:assert/strict'
import { readFile, readdir } from 'node:fs/promises'
import test from 'node:test'

import { renderFields } from '../resource-render/fields.ts'

const root = new URL('../../', import.meta.url)
const fixtures = new Map(
  await Promise.all(
    ['post', 'notice'].map(async (name) => [
      name,
      JSON.parse(
        await readFile(new URL(`./fixtures/resource-render/${name}.json`, import.meta.url), 'utf8'),
      ),
    ]),
  ),
)
const resourceFor = (name) => structuredClone(fixtures.get(name))

for (const name of ['post', 'notice']) {
  test(`${name} 字段模块与原生成资产逐文件、逐字节一致`, async () => {
    const files = renderFields(resourceFor(name), '1.3.0')
    const directory = new URL(`src/generated/resources/${name}/`, root)
    const expectedFiles = (
      await readdir(directory, { recursive: true, withFileTypes: true })
    ).filter(
      (entry) =>
        entry.isFile() &&
        !['api.ts', 'index.ts', 'registration.ts', 'page.vue'].includes(entry.name),
    )
    assert.equal(files.size, expectedFiles.length)
    for (const [path, content] of files) {
      assert.equal(content, await readFile(new URL(path, directory), 'utf8'), path)
    }
  })
}

test('宽模型与大量枚举递归分组，所有生成 TypeScript 文件保持 300 行以内', () => {
  const resource = resourceFor('post')
  const original = resource.fields.find((field) => field.name === 'name')
  resource.name = 'wide'
  resource.pascal_name = 'Wide'
  resource.fields = Array.from({ length: 801 }, (_, index) => ({
    ...structuredClone(original),
    name: `field_${index}`,
  }))
  resource.fields[0].enum_values = Object.fromEntries(
    Array.from({ length: 1001 }, (_, index) => [
      String(index),
      { zh_cn: `选项 ${index}`, en: `Option ${index}` },
    ]),
  )
  const files = renderFields(resource, '1.3.0')
  assert(files.has('form/group-0-0.ts'))
  assert(files.has('columns/group-0-0.ts'))
  assert(files.has('options/field_0/group-0-0.ts'))
  for (const [path, content] of files) {
    assert(content.replace(/\n$/, '').split('\n').length <= 300, path)
    assert(content.startsWith('// @generated by RyFrame 1.3.0\n'), path)
  }
})

test('拆分时仅提升导入路径，字段文案中的相似文本保持不变', () => {
  const resource = resourceFor('post')
  const original = resource.fields.find((field) => field.name === 'name')
  resource.fields = Array.from({ length: 32 }, (_, index) => ({
    ...structuredClone(original),
    name: `field_${index}`,
    labels: { zh_cn: "来自 from '../文案", en: "Label from '../literal" },
  }))
  const files = renderFields(resource, '1.3.0')
  assert(files.get('query/part-0.ts').includes("Label from '../literal"))
  assert(files.get('form/part-0.ts').includes("from '../api'"))
  assert(files.get('model.ts').includes("from './form'"))
})
