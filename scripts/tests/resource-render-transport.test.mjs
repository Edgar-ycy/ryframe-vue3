import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import vm from 'node:vm'
import ts from 'typescript'

import { renderTransport } from '../resource-render/transport.ts'
import { order } from './fixtures/resource-render/order-ir.mjs'

const generatorVersion = '1.3.0'
const assetNames = ['api.ts', 'page.vue', 'registration.ts', 'index.ts']
const fixtures = new Map()
const goldens = new Map()

// JSON 按后端 model.rs、Post/Notice 清单及 ownership 摘要人工构造；测试不加载后端代码。
for (const name of ['post', 'notice']) {
  fixtures.set(
    name,
    JSON.parse(
      await readFile(new URL(`./fixtures/resource-render/${name}.json`, import.meta.url), 'utf8'),
    ),
  )
  goldens.set(
    name,
    new Map(
      await Promise.all(
        assetNames.map(async (file) => [
          file,
          await readFile(new URL(`../../src/generated/resources/${name}/${file}`, import.meta.url)),
        ]),
      ),
    ),
  )
}

const fixture = (name = 'post') => structuredClone(fixtures.get(name))
const golden = (name, file) => goldens.get(name).get(file).toString('utf8')

test('tenant_data 注册精确三写权限，control_row 不进入业务维护限制', () => {
  const resource = order()
  const { create, update, delete: remove, list } = resource.access.permissions
  for (const storage of ['tenant_data', 'control_row']) {
    resource.storage = storage
    const source = renderTransport(resource, generatorVersion).get('registration.ts')
    const code = ts.transpileModule(source, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
    }).outputText
    const module = { exports: {} }
    vm.runInThisContext(`(function(require, module, exports) { ${code}\n})`)(
      (name) => {
        assert.equal(name, '@/features/pages')
        return { definePageManifest: (value) => value }
      },
      module,
      module.exports,
    )
    const manifest = module.exports.pageManifest
    assert.equal(manifest.pages[0].permissionCode, list)
    if (storage === 'tenant_data') {
      assert.deepEqual(manifest.businessWritePermissions, [create, update, remove])
    } else assert.equal(Object.hasOwn(manifest, 'businessWritePermissions'), false)
  }
})

function freeze(value) {
  if (value && typeof value === 'object') {
    Object.values(value).forEach(freeze)
    Object.freeze(value)
  }
  return value
}

for (const name of ['post', 'notice']) {
  test(`${name} 四类传输资产与现有生成文件逐字节一致`, () => {
    const resource = freeze(fixture(name))
    const before = JSON.stringify(resource)
    const result = renderTransport(resource, generatorVersion)
    assert.ok(result instanceof Map)
    assert.deepEqual([...result.keys()], assetNames)
    for (const [file, content] of result) {
      assert.equal(typeof content, 'string')
      assert.ok(content.endsWith('\n'))
      assert.ok(!content.includes('\r'))
      assert.deepEqual(Buffer.from(content, 'utf8'), goldens.get(name).get(file), file)
    }
    assert.equal(JSON.stringify(resource), before)
    assert.deepEqual(renderTransport(resource, generatorVersion), result)
  })
}

test('生成器版本由显式参数决定，中文头及其他字节保持不变', () => {
  const version = '9.8.7-transport-fixture'
  const result = renderTransport(fixture(), version)
  for (const [file, content] of result) {
    assert.equal(
      content,
      golden('post', file).replace(
        '@generated by RyFrame 1.3.0',
        `@generated by RyFrame ${version}`,
      ),
    )
    assert.ok(content.includes('请勿手工修改；修改资源清单后重新生成。'))
  }
  for (const invalid of [undefined, null, '', 13]) {
    assert.throws(() => renderTransport(fixture(), invalid), /必须显式提供生成器版本/u)
  }
})

test('business 资源使用 system operation 域，显式操作名和来源路径不被重推导', () => {
  const resource = fixture()
  Object.assign(resource, {
    name: 'work_order',
    pascal_name: 'WorkOrder',
    module: 'business',
    source_path: 'crates/work-orders/.ryframe/resources/work_order.toml',
  })
  for (const action of Object.keys(resource.api.operations)) {
    resource.api.operations[action] = resource.api.operations[action].replace(
      'system_posts',
      'system_work_orders',
    )
  }
  resource.api.operations.create = 'post_system_work_orders_submit'
  const api = renderTransport(resource, generatorVersion).get('api.ts')
  assert.equal(
    api,
    golden('post', 'api.ts')
      .replaceAll('Post', 'WorkOrder')
      .replaceAll('system_posts', 'system_work_orders')
      .replaceAll('post_system_work_orders', 'post_system_work_orders_submit')
      .replace('// resource: post\n', '// resource: work_order\n')
      .replace('catalog/resources/post.toml', resource.source_path),
  )
  assert.ok(!api.includes('/operations/business'))
  resource.module = 'platform'
  assert.equal(
    renderTransport(resource, generatorVersion).get('api.ts'),
    api.replace('/operations/system', '/operations/platform'),
  )
})

