test('仅无枚举的列表 DateTime 字段引入日期格式化，Date 与控件类型不触发', () => {
  const dated = golden('post', 'page.vue')
  const undated = dated
    .replace("import { formatLocalizedDate } from '@/i18n'\n", '')
    .replace(
      'createPostPresentation(translate, formatLocalizedDate)',
      'createPostPresentation(translate)',
    )
  for (const valueType of ['date_time', 'date', 'string']) {
    for (const list of [false, true]) {
      for (const withEnum of [false, true]) {
        const resource = fixture()
        const field = structuredClone(resource.fields.find((item) => item.name === 'created_at'))
        field.value_type = valueType
        field.usage.list = list
        field.widget = withEnum ? 'date_time' : 'text'
        field.enum_values = withEnum ? { active: { zh_cn: '正常', en: 'Active' } } : {}
        resource.fields = [field]
        assert.equal(
          renderTransport(resource, generatorVersion).get('page.vue'),
          valueType === 'date_time' && list && !withEnum ? dated : undated,
          `${valueType}/${list}/${withEnum}`,
        )
      }
    }
  }
  const empty = fixture()
  empty.fields = []
  assert.equal(renderTransport(empty, generatorVersion).get('page.vue'), undated)
})

test('手写 page 扩展仅改变注册 import，本地 page 和 index 仍完整生成', () => {
  const resource = fixture()
  const generated = renderTransport(resource, generatorVersion)
  resource.frontend_extensions.page = '@/views/business/work-order/index.vue'
  const handwritten = renderTransport(resource, generatorVersion)
  assert.equal(
    handwritten.get('registration.ts'),
    golden('post', 'registration.ts').replace(
      '@/views/system/post/index.vue',
      '@/views/business/work-order/index.vue',
    ),
  )
  for (const file of ['api.ts', 'page.vue', 'index.ts']) {
    assert.equal(handwritten.get(file), generated.get(file))
  }
  const expected = golden('post', 'registration.ts').replace(
    '@/views/system/post/index.vue',
    './page.vue',
  )
  delete resource.frontend_extensions.page
  assert.equal(renderTransport(resource, generatorVersion).get('registration.ts'), expected)
  for (const page of [null, false, 7, {}, []]) {
    resource.frontend_extensions.page = page
    assert.equal(renderTransport(resource, generatorVersion).get('registration.ts'), expected)
  }
})

test('capability 与系统租户限制独立投影，省略字段不增加限制', () => {
  for (const capability of [undefined, null, 'system.notice']) {
    for (const restricted of [undefined, false, true]) {
      const resource = fixture('notice')
      delete resource.access.capability
      delete resource.access.system_tenant_only
      if (capability !== undefined) resource.access.capability = capability
      if (restricted !== undefined) resource.access.system_tenant_only = restricted
      let expected = golden('notice', 'registration.ts')
      if (capability == null) expected = expected.replace('["system.notice"]', '[]')
      if (restricted)
        expected = expected.replace('      page:', '      requiresSystemTenant: true,\n      page:')
      assert.equal(renderTransport(resource, generatorVersion).get('registration.ts'), expected)
    }
  }
})
